export const EXAMPLE_DOCUMENT_TITLE = 'Notes from the bakery planning meeting';

export const EXAMPLE_DOCUMENT = `# Riverside Bakery — planning notes

We met on 12 March to go over where things stand before the lease is signed.

## What we are doing

Riverside Bakery is a small neighbourhood bakery on Mill Street. We want to open
six days a week with a short menu: sourdough, two pastries, and coffee. The point
is to be the place people walk to on a Saturday morning, not a destination
bakery.

## What we decided

We decided to sign the Mill Street lease rather than the unit by the station.
The station unit had more footfall but the rent was almost double, and the
kitchen would have needed a new extraction system.

We decided to open with a short menu and add to it later. Priya was firm that
trying to launch twelve products would mean doing all of them badly.

We agreed the opening date is 4 September.

## Where things stand

The lease is with the solicitor and should be signed by the end of the month.
The oven has been ordered and is due to arrive in July. We still do not have a
signed contract with the flour supplier, which is the main thing holding up the
costings.

Priya is running the kitchen. Tom is handling the money and the paperwork. We
have not decided who is doing social media, and honestly neither of us wants to.

## What happens next

Tom needs to chase the solicitor about the lease this week.
Priya is going to visit two flour suppliers before the end of the month.
We need to decide on opening hours before we order the signage.
Someone needs to look into whether we need a licence for tables on the pavement.

## How we like to work

Keep decisions written down in one place, because last time we had three
different versions of the budget and nobody knew which one was current.

Do not commit to anything over £2,000 without both of us agreeing first.
`;

